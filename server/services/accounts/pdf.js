/* PDF documents for Accounts (ledger statement, bills / orders / notes, quotation).
 * Port of NepalAccounts/server/app/pdfs.py, built on `pdfkit` (loaded lazily — the rest of the module
 * works without it; only the PDF endpoints need it installed on the server).
 *
 * Uses Arial from Windows when available (Nepali digit grouping, Latin text only — Arial has no
 * Devanagari glyphs, same as the demo); otherwise the built-in Helvetica.
 *
 * The quotation PDF is in quotePdf.js.
 */
import fs from 'fs';
import path from 'path';
import { bsStr } from './nepaliDate.js';
import { nepMoney } from './common.js';
import { getFile } from './files.js';

const FONT_DIR = path.join(process.env.WINDIR || 'C:\\Windows', 'Fonts');
const money = (n) => nepMoney(n);
const g = (n) => String(Math.round((Number(n) || 0) * 1000) / 1000);

const ONES = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
const TENS = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
const two = (n) => (n < 20 ? ONES[n] : TENS[Math.floor(n / 10)] + (n % 10 ? ` ${ONES[n % 10]}` : ''));
function words(n) {
  if (n === 0) return 'Zero';
  const parts = [];
  const crore = Math.floor(n / 1e7); n %= 1e7;
  const lakh = Math.floor(n / 1e5); n %= 1e5;
  const thousand = Math.floor(n / 1e3); n %= 1e3;
  if (crore) parts.push(`${words(crore)} Crore`);
  if (lakh) parts.push(`${two(lakh)} Lakh`);
  if (thousand) parts.push(`${two(thousand)} Thousand`);
  if (n) parts.push([Math.floor(n / 100) ? `${ONES[Math.floor(n / 100)]} Hundred` : '', n % 100 ? two(n % 100) : ''].filter(Boolean).join(' '));
  return parts.join(' ');
}
/** Nepali system (thousand, lakh, crore) — same wording as the screen. */
export function amountInWords(amount) {
  const v = Math.round(Math.abs(Number(amount) || 0) * 100);
  const rupees = Math.floor(v / 100), paisa = v % 100;
  return `Rupees ${words(rupees)}${paisa ? ` and ${two(paisa)} Paisa` : ''} Only`;
}
const bal = (n) => { n = Number(n) || 0; return Math.abs(n) < 0.005 ? '0.00' : `${money(n)} ${n > 0 ? 'Dr' : 'Cr'}`; };

async function loadKit() {
  try { return (await import('pdfkit')).default; } catch (e) {
    if (e.code === 'ERR_MODULE_NOT_FOUND') throw Object.assign(new Error('PDF support is not installed on the server yet (package "pdfkit"). Ask your administrator.'), { status: 501 });
    throw e;
  }
}

function hexRgb(h, d = [46, 125, 50]) {
  const m = /^#?([0-9a-f]{6})$/i.exec(h || '');
  return m ? [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)) : d;
}

/** Create a document + helpers. `finish()` stamps footers and resolves with the PDF Buffer. */
async function createDoc(footerText) {
  const PDFDocument = await loadKit();
  const doc = new PDFDocument({ size: 'A4', margin: 28, bufferPages: true, info: { Producer: 'eHajiri Accounts' } });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const reg = path.join(FONT_DIR, 'arial.ttf'), bold = path.join(FONT_DIR, 'arialbd.ttf');
  const uni = fs.existsSync(reg) && fs.existsSync(bold);
  if (uni) { doc.registerFont('Body', reg); doc.registerFont('BodyB', bold); }
  const face = (b) => (uni ? (b ? 'BodyB' : 'Body') : (b ? 'Helvetica-Bold' : 'Helvetica'));
  // Arial has no Devanagari glyphs: keep the Latin text only
  const txt = (s) => String(s ?? '').replace(/[\u0900-\u097F]/g, '').trim();
  const PAGE_W = doc.page.width, M = 28, CW = PAGE_W - M * 2;
  const font = (b, size) => doc.font(face(b)).fontSize(size);
  const cell = (s, x, y, w, h, { align = 'left', border = true, fill = null, bold: b = false, size = 8.5, color = '#000' } = {}) => {
    if (fill) doc.save().rect(x, y, w, h).fill(fill).restore();
    if (border) doc.save().lineWidth(0.5).strokeColor('#555').rect(x, y, w, h).stroke().restore();
    font(b, size).fillColor(color).text(txt(s), x + 2, y + (h - size) / 2 - 0.5, { width: w - 4, align, lineBreak: false, ellipsis: true });
  };
  const finish = () => new Promise((resolve, reject) => {
    const range = doc.bufferedPageRange();
    for (let i = 0; i < range.count; i++) {
      doc.switchToPage(range.start + i);
      doc.page.margins.bottom = 0;
      font(false, 7).fillColor('#787878');
      doc.text(txt(footerText), M, doc.page.height - 24, { width: CW / 2, align: 'left', lineBreak: false });
      doc.text(`Page ${i + 1}/${range.count}`, M + CW / 2, doc.page.height - 24, { width: CW / 2, align: 'right', lineBreak: false });
    }
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
  return { doc, M, CW, font, cell, txt, finish, bottom: () => doc.page.height - 40 };
}

const stamp = (user) => `Generated by ${user} on ${new Date().toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short' })} · eHajiri Accounts`;

function header(k, company, title, sub) {
  const { doc, M, CW, font, txt } = k;
  font(true, 14).fillColor('#000').text(txt(company.name), M, 28, { width: CW, align: 'center' });
  const line2 = [company.address, company.pan && `${company.vat_registered ? 'VAT' : 'PAN'} No: ${company.pan}`, company.phone && `Ph: ${company.phone}`].filter(Boolean).join(' · ');
  if (line2) font(false, 8.5).text(txt(line2), M, doc.y + 1, { width: CW, align: 'center' });
  if (title) font(true, 12).text(title, M, doc.y + 6, { width: CW, align: 'center' });
  for (const s of sub || []) font(false, 9.5).text(txt(s), M, doc.y + 1, { width: CW, align: 'center' });
  doc.moveDown(0.5);
}

export async function ledgerPdf(company, data, dateFrom, dateTo, user) {
  const k = await createDoc(stamp(user));
  const { doc, M, font, cell, bottom } = k;
  const acc = data.account;
  header(k, { ...company, vat_registered: 0, pan: company.pan }, 'Ledger Statement',
    [`${acc.name}  (${acc.group_name})`, acc.pan ? `PAN: ${acc.pan}` : null, `${bsStr(dateFrom)} to ${bsStr(dateTo)} (BS)`].filter(Boolean));
  const widths = [52, 70, 175, 60, 60, 66], heads = ['Miti', 'Voucher No.', 'Particulars', 'Debit', 'Credit', 'Balance'], aligns = ['left', 'left', 'left', 'right', 'right', 'right'];
  let y = doc.y + 6;
  const headRow = () => { let x = M; heads.forEach((h, i) => { cell(h, x, y, widths[i], 17, { align: aligns[i], fill: '#efefef', bold: true }); x += widths[i]; }); y += 17; };
  const row = (cells, { bold = false, fill = null, sub = [] } = {}) => {
    const h = 15 + sub.length * 10;
    if (y + h > bottom()) { doc.addPage(); y = 36; headRow(); }
    let x = M;
    cells.forEach((c, i) => { cell(c, x, y, widths[i], h, { align: aligns[i], bold, fill }); x += widths[i]; });
    sub.forEach((s, j) => font(false, 7).fillColor('#5a5a5a').text(k.txt(s).slice(0, 78), M + widths[0] + widths[1] + 3, y + 13 + j * 10, { width: widths[2] - 6, lineBreak: false }));
    y += h;
  };
  headRow();
  row(['', '', 'Opening balance', '', '', bal(data.opening)], { bold: true, fill: '#f7faf9' });
  for (const r of data.rows) {
    const part = r.memo ? r.particulars : `${r.dr > 0 ? 'By ' : 'To '}${r.particulars || ''}`;
    let sub = (r.items || []).map((i) => `${i.item} x ${g(i.qty)} ${i.unit} @ ${money(i.rate)}${i.discount ? ` - disc ${money(i.discount)}` : ''} = ${money(i.amount)}`);
    if (sub.length && r.bill) {
      const b = r.bill;
      sub.push(`Gross ${money(b.gross)}${b.discount ? `  ·  Discount ${money(b.discount)}` : ''}  ·  VAT ${money(b.vat)}  ·  Total ${money(b.total)}`);
    }
    if (r.narration && !sub.length) sub = [String(r.narration).slice(0, 90)];
    row([bsStr(r.vdate), r.voucher_no, part.slice(0, 48), r.dr ? money(r.dr) : '', r.cr ? money(r.cr) : '', bal(r.balance)], { sub });
  }
  row(['', '', 'Period total', money(data.total_dr), money(data.total_cr), ''], { bold: true, fill: '#f7faf9' });
  row(['', '', 'Closing balance', '', '', bal(data.closing)], { bold: true, fill: '#f7faf9' });
  return k.finish();
}

const DOC_TITLES = { PO: 'PURCHASE ORDER', PB: 'PURCHASE ENTRY', PR: 'DEBIT NOTE', SO: 'SALES ORDER', SI: 'TAX INVOICE', SR: 'CREDIT NOTE', QT: 'QUOTATION' };
const PAY = { credit: 'Credit', cash: 'Cash', cheque: 'Cheque', bank: 'QR / Bank Transfer' };

/** Bill / order / note as an A4 PDF (same layout as the printed bill). */
export async function docPdf(company, d, user) {
  const k = await createDoc(stamp(user));
  const { doc, M, CW, font, cell, txt, bottom } = k;
  const sale = ['SO', 'SI', 'SR'].includes(d.doc_type);
  let title = DOC_TITLES[d.doc_type];
  if (d.doc_type === 'SI' && !company.vat_registered) title = 'INVOICE';
  header(k, company, title);
  if (d.status === 'cancelled') font(true, 10).fillColor('#c80000').text(txt(`CANCELLED — ${d.cancel_reason || ''}`), M, doc.y, { width: CW, align: 'center' });
  doc.moveDown(0.4);

  const who = sale ? 'Buyer' : 'Supplier';
  const left = [`${who}: ${d.party_name}`];
  if (d.party_address) left.push(`Address: ${d.party_address}`);
  left.push(`${who}'s PAN: ${d.party_pan || '-'}`);
  if (d.supplier_bill_no) left.push(`Supplier bill no: ${d.supplier_bill_no}`);
  const nos = [d.challan_no && `Challan No: ${d.challan_no}`, d.vat_bill_no && `VAT Bill No: ${d.vat_bill_no}`].filter(Boolean);
  if (nos.length) left.push(nos.join(' · '));
  const noWord = d.doc_type === 'SI' ? 'Invoice' : d.type_name;
  const right = [`${noWord} No: ${d.doc_no}`, `Miti: ${bsStr(d.doc_date)}`, `Date: ${d.doc_date}`, `Payment: ${PAY[d.payment_mode] || d.payment_mode}${d.cash_account ? ` - ${d.cash_account}` : ''}`];
  if (d.payment_mode === 'cheque' && d.cheque_no) right.push(`Cheque ${d.cheque_no} (${d.cheque_bank || ''}) dated ${bsStr(d.cheque_date)}`);
  if (d.payment_mode === 'bank' && d.txn_id) right.push(`Trans. ID: ${d.txn_id}`);
  if (d.due_date && d.payment_mode === 'credit') right.push(`Due date: ${bsStr(d.due_date)}`);
  let y = doc.y + 4;
  const n = Math.max(left.length, right.length);
  for (let i = 0; i < n; i++) {
    font(false, 9).fillColor('#000');
    if (left[i]) doc.text(txt(left[i]), M, y + i * 12, { width: CW / 2, lineBreak: false, ellipsis: true });
    if (right[i]) doc.text(txt(right[i]), M + CW / 2, y + i * 12, { width: CW / 2, align: 'right', lineBreak: false, ellipsis: true });
  }
  y += n * 12 + 8;

  const widths = [26, 190, 55, 40, 36, 62, 45, 52], heads = ['S.N.', 'Particulars', 'HS Code', 'Qty', 'Unit', 'Rate', 'Disc.', 'Amount'];
  const aligns = ['center', 'left', 'left', 'right', 'left', 'right', 'right', 'right'];
  const headRow = () => { let x = M; heads.forEach((h, i) => { cell(h, x, y, widths[i], 17, { align: aligns[i], fill: '#efefef', bold: true }); x += widths[i]; }); y += 17; };
  headRow();
  d.lines.forEach((l, idx) => {
    const sub = [];
    if (l.serials?.length) sub.push(`S/N: ${l.serials.join(', ')}`);
    if (l.warranty_until) sub.push(`Warranty ${l.warranty_months} months - till ${bsStr(l.warranty_until)}`);
    if (l.service_to) sub.push(`Service ${bsStr(l.service_from)} to ${bsStr(l.service_to)}`);
    const h = 15 + sub.length * 10;
    if (y + h > bottom() - 110) { doc.addPage(); y = 36; headRow(); }
    const cells = [String(idx + 1), l.item, l.hs_code || '', g(l.qty), l.unit || '', money(l.rate_excl), l.discount ? money(l.discount) : '', money(l.amount)];
    let x = M;
    cells.forEach((c, i) => { cell(c, x, y, widths[i], h, { align: aligns[i] }); x += widths[i]; });
    sub.forEach((s, j) => font(false, 7).fillColor('#5a5a5a').text(txt(s).slice(0, 70), M + widths[0] + 3, y + 13 + j * 10, { width: widths[1] - 6, lineBreak: false }));
    y += h;
  });

  y += 8;
  if (y + 90 > bottom()) { doc.addPage(); y = 36; }
  font(false, 8.5).fillColor('#000').text(txt(`In words: ${amountInWords(d.total)}`), M, y, { width: 270 });
  let yl = doc.y;
  if (d.narration) { doc.text(txt(`Remarks: ${d.narration}`), M, yl + 2, { width: 270 }); yl = doc.y; }
  const rows = [['Gross amount', d.gross, '#e8f1ff']];
  if (d.discount) rows.push(['Discount', d.discount, '#f8f8f8']);
  if (d.exempt) rows.push(['Non-taxable amount', d.exempt, '#f8f8f8']);
  if (Math.abs((d.taxable || 0) - (d.gross || 0)) > 0.005) rows.push(['Taxable amount', d.taxable, '#f8f8f8']);
  rows.push([`VAT ${g(company.vat_rate ?? 13)}%`, d.vat, '#fff4de'], ['Grand Total', d.total, '#def7e8']);
  let ry = y;
  for (const [label, v, fill] of rows) {
    const grand = label === 'Grand Total';
    cell(label, M + 300, ry, 130, 18, { fill, bold: grand, size: grand ? 9.5 : 8.5 });
    cell(money(v), M + 430, ry, 77, 18, { fill, bold: grand, align: 'right', size: grand ? 9.5 : 8.5 });
    ry += 18;
  }
  let sy = Math.max(ry, yl) + 46;
  if (sy > bottom()) { doc.addPage(); sy = 80; }
  [[M, `Prepared by: ${d.created_by}`], [M + 190, 'Received by'], [M + 380, 'Authorised signature']].forEach(([x, s]) => {
    doc.save().lineWidth(0.5).strokeColor('#000').moveTo(x, sy).lineTo(x + 130, sy).stroke().restore();
    font(false, 8.5).fillColor('#000').text(txt(s), x, sy + 3, { width: 130, align: 'center', lineBreak: false });
  });
  return k.finish();
}

